#!/usr/bin/env bash
# Downloads the open-source StevenBlack "porn-only" hosts list and converts it into
# the plain-domain format used by SafeSpace Guard. Run it on your own computer.
set -euo pipefail

URL="https://raw.githubusercontent.com/StevenBlack/hosts/master/alternates/porn-only/hosts"
OUT="$(dirname "$0")/../app/src/main/assets/blocklist.txt"

echo "Downloading blocklist..."
curl -fsSL "$URL" \
  | grep -E '^0\.0\.0\.0 ' \
  | cut -d' ' -f2 \
  | grep -vE '^(0\.0\.0\.0|localhost)$' \
  | sort -u > "$OUT.tmp"

{
  echo "# Generated by scripts/update_blocklist.sh from StevenBlack/hosts (porn-only)."
  cat "$OUT.tmp"
} > "$OUT"
rm "$OUT.tmp"

echo "Done: $(wc -l < "$OUT") lines written to $OUT"
